"""
apple.py
Everything about the apple:

  * make_apple_mesh()  -> writes a procedural apple-shaped OBJ (top and bottom dimples,
                          slightly fuller shoulders, faint 5-lobe profile)
  * add_to_model()     -> inserts the apple (free-floating physical body) and its stand
                          into the MJCF tree while build_model.py runs
  * AppleTracker       -> runtime helper: position, velocity, which hand touches it

Physics design
  * Collision shape is a sphere (radius APPLE_RADIUS): the most stable shape for
    grasping, rolling and catching. The detailed mesh is visual only.
  * Mass and inertia are set explicitly (solid sphere: I = 2/5 m r^2).
  * condim=6 adds torsional and rolling friction, so the apple does not spin or
    roll away on the stand or inside the fingers.
  * priority=1 makes the apple's contact settings win against the fingers'.
  * solref time constant 0.005 s (>= 2 x timestep) with damping ratio 1 gives a
    firm, critically damped contact: no rubber-ball bouncing.
"""

import math
import xml.etree.ElementTree as ET

import numpy as np

import config


# ------------------------------------------------------------------ geometry
def _fmt(v):
    return " ".join(f"{float(x):.6g}" for x in v)


def apple_surface(phi, theta, r):
    """Point on the apple surface. phi: 0 (top) .. pi (bottom), theta: around."""
    rho = r * (1.0 + 0.07 * math.cos(phi))                    # fuller shoulders
    rho *= 1.0 + 0.015 * math.cos(5 * theta) * math.sin(phi)   # faint 5 lobes
    z = r * math.cos(phi) * (1.0 + 0.07 * math.cos(phi))
    z -= 0.22 * r * math.exp(-(phi / 0.38) ** 2)               # stem dimple
    z += 0.10 * r * math.exp(-((math.pi - phi) / 0.42) ** 2)   # bottom dimple
    return rho * math.sin(phi) * math.cos(theta), rho * math.sin(phi) * math.sin(theta), z


def make_apple_mesh(path, r, n_phi=30, n_theta=48):
    """Write a closed, outward-facing triangle mesh. Returns z of the stem dimple."""
    verts = [apple_surface(0.0, 0.0, r)]
    for i in range(1, n_phi):
        phi = math.pi * i / n_phi
        for k in range(n_theta):
            verts.append(apple_surface(phi, 2 * math.pi * k / n_theta, r))
    verts.append(apple_surface(math.pi, 0.0, r))
    verts = np.array(verts)
    verts[:, 2] -= verts[:, 2].min() + r          # lowest point touches the sphere bottom

    faces = []
    ring = lambda i, k: 1 + (i - 1) * n_theta + (k % n_theta)   # noqa: E731
    bottom = len(verts) - 1
    for k in range(n_theta):
        faces.append((0, ring(1, k), ring(1, k + 1)))
    for i in range(1, n_phi - 1):
        for k in range(n_theta):
            a, b = ring(i, k), ring(i, k + 1)
            c, d = ring(i + 1, k), ring(i + 1, k + 1)
            faces += [(a, c, d), (a, d, b)]
    for k in range(n_theta):
        faces.append((bottom, ring(n_phi - 1, k + 1), ring(n_phi - 1, k)))

    with open(path, "w", encoding="utf-8") as f:
        f.write("# procedural apple generated by apple.py\n")
        for v in verts:
            f.write(f"v {v[0]:.6f} {v[1]:.6f} {v[2]:.6f}\n")
        for a, b, c in faces:
            f.write(f"f {a + 1} {b + 1} {c + 1}\n")
    return float(verts[0, 2]), verts, np.array(faces)


def apple_rest_position():
    x, y = config.APPLE_START_XY
    return (x, y, config.STAND_TOP_Z + config.APPLE_RADIUS + 0.0005)


# ------------------------------------------------------------------ MJCF
def add_to_model(root):
    """Add apple + stand to the MJCF root (called by build_model.py)."""
    r, m = config.APPLE_RADIUS, config.APPLE_MASS
    mesh_path = config.ROBOT_DIR / "apple.obj"
    config.ROBOT_DIR.mkdir(parents=True, exist_ok=True)
    top_z, _, _ = make_apple_mesh(mesh_path, r)

    asset = root.find("asset")
    asset.append(ET.Element("mesh", name="apple_mesh", file=mesh_path.resolve().as_posix()))
    asset.append(ET.Element("material", name="apple_skin", rgba="0.72 0.04 0.05 1",
                            specular="0.55", shininess="0.7", reflectance="0.05"))
    asset.append(ET.Element("material", name="apple_stem", rgba="0.33 0.20 0.09 1",
                            specular="0.1"))
    asset.append(ET.Element("material", name="apple_leaf", rgba="0.20 0.50 0.12 1",
                            specular="0.3"))
    asset.append(ET.Element("material", name="stand_mat", rgba="0.85 0.85 0.82 1",
                            specular="0.3", shininess="0.4"))

    wb = root.find("worldbody")

    # ---- stand (static: a body with no joint is welded to the world)
    sx, sy = config.APPLE_START_XY
    top = config.STAND_TOP_Z
    stand = ET.SubElement(wb, "body", name="apple_stand", pos=_fmt((sx, sy, 0)))
    ET.SubElement(stand, "geom", name="stand_base", type="cylinder", size="0.10 0.006",
                  pos="0 0 0.006", material="stand_mat")
    ET.SubElement(stand, "geom", name="stand_column", type="cylinder",
                  size=_fmt((0.018, (top - 0.02) / 2)), pos=_fmt((0, 0, (top - 0.02) / 2 + 0.012)),
                  material="stand_mat")
    ET.SubElement(stand, "geom", name="stand_top", type="cylinder",
                  size=_fmt((config.STAND_TOP_RADIUS, 0.008)), pos=_fmt((0, 0, top - 0.008)),
                  material="stand_mat", friction="1 0.01 0.002")

    # ---- apple
    apple = ET.SubElement(wb, "body", name="apple", pos=_fmt(apple_rest_position()))
    ET.SubElement(apple, "freejoint", name="apple_free")
    inertia = 0.4 * m * r * r
    ET.SubElement(apple, "inertial", pos="0 0 0", mass=f"{m:.6g}",
                  diaginertia=_fmt((inertia, inertia, inertia)))
    ET.SubElement(apple, "geom", name="apple_collision", type="sphere", size=f"{r:.6g}",
                  group="3", rgba="1 0 0 0.3", condim="6", priority="1",
                  friction=_fmt(config.APPLE_FRICTION), solref="0.005 1",
                  solimp="0.95 0.99 0.001 0.5 2", margin="0.001")
    ET.SubElement(apple, "geom", name="apple_visual", type="mesh", mesh="apple_mesh",
                  material="apple_skin", contype="0", conaffinity="0", group="2", mass="0")
    k = r / 0.035                                   # stem and leaf scale with the apple
    stem_base = np.array((0.0, 0.0, top_z - 0.002 * k))
    stem_tip = stem_base + k * np.array((0.003, 0.002, 0.018))
    ET.SubElement(apple, "geom", name="apple_stem", type="capsule", size=f"{0.0022 * k:.5f}",
                  fromto=_fmt(list(stem_base) + list(stem_tip)), material="apple_stem",
                  contype="0", conaffinity="0", group="2", mass="0")
    ET.SubElement(apple, "geom", name="apple_leaf", type="ellipsoid",
                  size=_fmt(k * np.array((0.013, 0.0055, 0.0012))),
                  pos=_fmt(stem_base + k * np.array((0.011, 0.0, 0.009))),
                  quat="0.95 0.15 -0.22 0.1", material="apple_leaf",
                  contype="0", conaffinity="0", group="2", mass="0")


# ------------------------------------------------------------------ runtime
class AppleTracker:
    """Read-only view of the apple's state during the simulation."""

    def __init__(self, model, data):
        import mujoco
        self._mj = mujoco
        self.m, self.d = model, data
        self.body = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_BODY, "apple")
        if self.body < 0:
            raise ValueError("No 'apple' body in the model; run: python main.py build")
        jid = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_JOINT, "apple_free")
        self.qadr = int(model.jnt_qposadr[jid])
        self.dadr = int(model.jnt_dofadr[jid])
        self.geom = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_GEOM, "apple_collision")
        self.owner = {}
        for b in range(model.nbody):
            name = mujoco.mj_id2name(model, mujoco.mjtObj.mjOBJ_BODY, b) or ""
            if name.startswith("lh_"):
                self.owner[b] = "left"
            elif name.startswith("rh_"):
                self.owner[b] = "right"
            elif name == "apple_stand":
                self.owner[b] = "stand"
            elif b == 0:
                self.owner[b] = "floor"

    @property
    def pos(self):
        return self.d.qpos[self.qadr:self.qadr + 3].copy()

    @property
    def vel(self):
        return self.d.qvel[self.dadr:self.dadr + 3].copy()

    def pos_in(self, d):
        return d.qpos[self.qadr:self.qadr + 3].copy()

    def vel_in(self, d):
        return d.qvel[self.dadr:self.dadr + 3].copy()

    def contacts(self, data=None):
        """{'left': n, 'right': n, 'stand': n, 'floor': n, 'other': n}.
        Pass `data` to inspect a different MjData (e.g. a planning rollout)."""
        d = self.d if data is None else data
        out = {"left": 0, "right": 0, "stand": 0, "floor": 0, "other": 0}
        for c in d.contact[:d.ncon]:
            if self.geom not in (c.geom1, c.geom2):
                continue
            other = c.geom2 if c.geom1 == self.geom else c.geom1
            out[self.owner.get(int(self.m.geom_bodyid[other]), "other")] += 1
        return out

    def set_free_state(self, pos, vel=(0, 0, 0)):
        """Only for test harnesses (e.g. the drop test). Never used in the toss."""
        self.d.qpos[self.qadr:self.qadr + 3] = pos
        self.d.qpos[self.qadr + 3:self.qadr + 7] = (1, 0, 0, 0)
        self.d.qvel[self.dadr:self.dadr + 6] = 0
        self.d.qvel[self.dadr:self.dadr + 3] = vel
