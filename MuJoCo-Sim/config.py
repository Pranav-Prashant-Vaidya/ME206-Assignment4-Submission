def find_menagerie():
    """Return the MuJoCo Menagerie folder (the one containing unitree_g1/)."""
    candidates = []
    if os.environ.get("MENAGERIE_PATH"):
        candidates.append(Path(os.environ["MENAGERIE_PATH"]).expanduser())
    candidates += [
        PROJECT_DIR / "mujoco_menagerie",
        PROJECT_DIR / "mujoco_menagerie-main",
        PROJECT_DIR.parent / "mujoco_menagerie",
        PROJECT_DIR.parent / "mujoco_menagerie-main",
        Path.home() / "mujoco_menagerie",            # your install is here
        Path.home() / "mujoco_menagerie-main",
    ]
    for c in candidates:
        if (c / "unitree_g1" / "g1.xml").exists() and (c / "shadow_hand").is_dir():
            return c.resolve()
    raise FileNotFoundError(
        "MuJoCo Menagerie not found. Set the MENAGERIE_PATH environment variable "
        "to the folder that contains unitree_g1/ and shadow_hand/.\nSearched:\n  "
        + "\n  ".join(str(c) for c in candidates))


