def apply_fast_graphics(model, viewer=None):
    """Lighter rendering for slow laptops (see FAST_GRAPHICS in config.py)."""
    import mujoco
    model.vis.quality.shadowsize = SHADOW_SIZE
    if viewer is not None and FAST_GRAPHICS:
        with viewer.lock():
            viewer.user_scn.flags[mujoco.mjtRndFlag.mjRND_SHADOW] = 0
            viewer.user_scn.flags[mujoco.mjtRndFlag.mjRND_REFLECTION] = 0
            viewer.user_scn.flags[mujoco.mjtRndFlag.mjRND_SKYBOX] = 0
